"""Repack a ROM zip with a replaced image, streaming every entry."""

from __future__ import annotations

import copy
import os
import shutil
import tempfile
import zipfile
from pathlib import Path

from .errors import UserError


def repack_zip(src_zip: Path, member: str, new_image: Path, dest: Path) -> Path:
    """Copy `src_zip` to `dest`, replacing `member` by `new_image`.

    Entries keep their ZipInfo (name, date, compression, attributes). The archive
    comment (whole-file signature) is dropped. `dest` only appears on success.
    """
    dest = Path(dest)
    dest.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=dest.parent, prefix=dest.name + ".", suffix=".part")
    os.close(fd)
    try:
        with zipfile.ZipFile(src_zip) as zin:
            if member not in zin.namelist():
                raise UserError(f"{member} not found in {src_zip}")
            with zipfile.ZipFile(tmp, "w", allowZip64=True) as zout:
                for info in zin.infolist():
                    new_info = copy.copy(info)
                    new_info.extra = b""  # zip64 extra is regenerated by zipfile
                    new_info.flag_bits &= 0x800  # keep only the UTF-8 name flag
                    if info.filename == member:
                        new_info.file_size = new_info.compress_size = new_info.CRC = 0
                        size = Path(new_image).stat().st_size
                        src = open(new_image, "rb")
                    else:
                        size = info.file_size
                        src = zin.open(info)
                    with src, zout.open(new_info, "w", force_zip64=size >= zipfile.ZIP64_LIMIT) as out:
                        shutil.copyfileobj(src, out, 1 << 20)
        os.replace(tmp, dest)
    except zipfile.BadZipFile as e:
        raise UserError(f"{src_zip} is not a valid zip: {e}") from None
    finally:
        if os.path.exists(tmp):
            os.unlink(tmp)
    return dest
